/// The clock the `move` rate limiter stamps into `last_move_tick`.
///
/// `arena.tick` is the contract's source (D16) and is correct during a fight. It is
/// *not* correct in the lobby: `boss_tick` returns before incrementing unless
/// `phase == PHASE_FIGHTING`, so a tick-only limiter would grant each player exactly
/// one lobby move ever and then freeze them short of the gate — no match could ever
/// start. The ER's 50 ms slot is the only other monotonic counter available on this
/// side of the boundary, so the lobby uses that. The open arena makes this more
/// load-bearing, not less: the lobby is now 60x20 tiles of unobstructed floor and the
/// gate is one 8-tile slot in the far wall, so the walk to it is a long straight run
/// that a one-move-per-400 ms limiter would turn back into wading.
///
/// The comparison against the stamp is `!=`, not `>`. Swapping sources at the phase
/// flip leaves a stamp from the other clock in the field (a slot number dwarfs a
/// tick), and `>` would then freeze every player for the entire match. Neither clock
/// can be rewound by a caller, so `!=` is exactly as tight: one accepted move per
/// tick while fighting, one per 50 ms slot in the lobby.
///
/// The stamp this writes is now read by a second rule: `shoot::fire` measures the charged
/// shot's hold as `Clock::get()?.slot − last_move_tick`, slot against slot. That is only a
/// duration because this function stamps the slot in **every** phase — the day it returns
/// `arena.tick` for any phase again, a charge becomes a subtraction across two clocks.
///
/// ponytail: `slot as u32` truncates, so one move is dropped every ~2^32 slots
/// (~6.8 years of ER uptime). Widening `last_move_tick` is a layout change; it is
/// not worth one.
fn move_clock(arena: &Arena) -> Result<u32, ProgramError> {
    // The ER slot, in every phase.
    //
    // This used to return `arena.tick` during a fight, and that single line was the whole
    // of "the game feels sluggish": `MOVE_STEP` is one 16-unit tile and the gate is one
    // move per clock unit, so a 400 ms tick capped movement at 2.5 tiles a second across
    // a 64-tile arena — twenty-five seconds to cross it. The lobby, which already used
    // the 50 ms slot, moved eight times faster, so walking to the gate felt fine and the
    // raid itself felt like wading.
    //
    // Raising the crank instead would have worked and cost far more: every tick-denominated
    // constant in the simulation (bullet velocity, RESPAWN_TICKS, the enrage deadline,
    // the shot cooldown) is expressed in ticks and would have to be rescaled together,
    // and the validator would do 4-8x the work to produce a purely visual result that
    // interpolation already provides. The boss simulation is genuinely happy at 400 ms;
    // only the player's input gate needed to be finer than the simulation it feeds.
    //
    // The limiter is not weakened, only re-scaled: still exactly one move per clock unit,
    // and the ER coalesces account notifications to one per 50 ms slot anyway, so this is
    // the finest granularity a client could observe its own move landing at.
    let _ = arena;
    Ok(Clock::get()?.slot as u32)
}

/// Land an accepted step on the seat: position, body direction, the client's sequence
/// echo and the rate-limit stamp, in one write.
///
/// `last_move_seq` echoes the client's input sequence number back. Without it an arriving
/// position is ambiguous as to which input produced it and prediction cannot be
/// reconciled; the symptom is rubber-banding for every player (D14).
///
/// Split out of [`move_player`] for one reason: `facing` is also where `shoot::fire` parks
/// the charged-shot flag (`state::CHARGED_SHOT_BIT`), and this write assigning a **bare
/// octant** is what clears it — a step ends the drawn arrow's lifetime with no second field
/// to expire. That is a rule the client mirrors, so it is asserted below against this
/// function rather than read off an assignment inside a handler no host test can call.
fn commit_move(slot: &mut PlayerSlot, dir: u8, (x, y): (i16, i16), seq: u16, now: u32) {
    slot.x = x;
    slot.y = y;
    slot.facing = dir;
    slot.last_move_seq = seq;
    slot.last_move_tick = now;
}

/// Accounts must be validated before any state is touched, and every guard below
/// takes `&AccountView` — which means all of them have to run *before* the `RefMut`
/// borrows, not interleaved with them.
///
/// `players` is bound to `arena` by re-deriving its PDA from the arena address, which
/// is what stops a caller pairing match A's arena with match B's players. `arena`
/// itself is checked by owner + discriminator only: nothing but this program can
/// mint an account it owns, so re-deriving `[b"arena", arena_id]` would buy nothing
/// for ~1.5K CU.
///
/// Returns the arena address, since the `RefMut` on `arena` makes it unreachable
/// afterwards.
fn validate_pair(
    program_id: &Address,
    arena_ai: &AccountView,
    players_ai: &AccountView,
    authority_ai: &AccountView,
    arena_writable: bool,
) -> Result<Address, ProgramError> {
    assert_signer(authority_ai)?;
    assert_writable(players_ai)?;
    if arena_writable {
        assert_writable(arena_ai)?;
    }
    // Inside the ER a delegated account keeps its original owner; on base layer it
    // would be the delegation program. These three handlers only ever run on the ER.
    assert_owned_by(arena_ai, program_id)?;
    assert_owned_by(players_ai, program_id)?;

    let arena_key = *arena_ai.address();
    // `assert_pda` searches for the canonical bump itself (guards.rs) — the stored bump
    // is never a seed. Passing it as one derives a different address entirely, which
    // rejects every legitimate call.
    assert_pda(players_ai, &[SEED_PLAYERS, arena_key.as_ref()], program_id)?;
    Ok(arena_key)
}

/// Quantize the client's requested direction vector to one of the eight `facing`
/// octants, indexing `MOVE_STEP`.
///
/// The wire carries `dx`/`dy` (frozen ABI, tag 6) but the *displacement* is not the
/// client's to choose: only the sign of each component is read, and the step itself
/// comes off `MOVE_STEP` here. That is the "per-tick speed cap" `instruction.rs`
/// defers to the handler — a client that sends (127, 127) moves exactly one diagonal
/// step south-east, the same as one that sends (1, 1). Magnitude is ignored rather
/// than rejected so the caller may send either a unit vector or a full step vector.
///
/// The mapping is the one `app/src/input/controls.ts::dirFromVector` computes with
/// `atan2`: 0 N, 1 NE, 2 E, 3 SE, 4 S, 5 SW, 6 W, 7 NW, y down. `(0, 0)` is not a
/// direction and is rejected at the boundary.
///
/// **Nearest of eight, not sign-only.** The sign quadrant answers "which of the four
/// diagonals" for every vector that is not exactly axis-aligned, so `(120, -7)` — a
/// thumbstick 3° off due east — used to resolve to north-east, 45° away. Free aim gives
/// `shoot` a raw `(dx, dy)` pair off a pointer, and `shoot` stamps `facing` from it
/// through this function, so sign-only would have every shot in the pit flip the sprite
/// to a diagonal. The octant boundary is 22.5°, and `tan 22.5° = 0.41421`, approximated
/// as `5/12 = 0.41667` — 0.15° of error at the boundary, in integers, with no table and
/// no float. Both products fit `i32` at the `i8` input range with three orders of
/// magnitude to spare.
///
/// Answers identically to the old body on all eight unit vectors, which is what its test
/// asserts and why that test is not edited.
pub(crate) fn octant(dx: i8, dy: i8) -> Result<u8, ProgramError> {
    let (x, y) = (dx as i32, dy as i32);
    if x == 0 && y == 0 {
        return Err(ProgramError::InvalidInstructionData);
    }
    let (ax, ay) = (x.abs(), y.abs());
    Ok(if 12 * ay < 5 * ax {
        // Inside 22.5° of the x axis.
        if x > 0 {
            2
        } else {
            6
        }
    } else if 12 * ax < 5 * ay {
        // Inside 22.5° of the y axis.
        if y < 0 {
            0
        } else {
            4
        }
    } else {
        // The diagonal band. Neither component can be zero here: a zero component
        // makes one of the two tests above true for any non-zero vector.
        match (x > 0, y > 0) {
            (true, false) => 1,
            (true, true) => 3,
            (false, true) => 5,
            (false, false) => 7,
        }
    })
}

/// The three phases in which a seat may act. Everything else is a fight that is over.
///
/// `LOBBY`, `MUSTERING` and `FIGHTING` are the only phases in which player input means
/// anything, and this is the allow-list rather than a deny-list of the other four for a
/// reason: the phase byte has grown twice now — four values to six (`PHASE_ROLLING`,
/// `PHASE_ROLLED`), then six to seven (`PHASE_MUSTERING`) — and a handler written as
/// `phase != PHASE_SETTLING && phase != PHASE_SETTLED` would have silently started
/// accepting moves during a VRF roll. An allow-list gains nothing when a phase is
/// appended; a deny-list loses a rule.
///
/// `MUSTERING` is the muster window: the gate is open, the countdown to `fight_at_tick` is
/// running, and everyone walks and joins exactly as they did in the lobby. Only weapons
/// stay down, and that costs nothing here — `shoot` tests `== PHASE_FIGHTING` directly, so
/// it refuses through the muster without a line of its own.
///
/// What each refusal prevents:
///
/// - `SETTLING` / `ROLLED`: `outcome` is fixed and the leaderboard will be written from
///   these bytes. A move accepted here changes a match that is already scored.
/// - `ROLLING`: a VRF callback is in flight against this arena. Player writes are not the
///   hazard — committing is — but there is no fight to move in either.
/// - `SETTLED`: the accounts are on their way back to base layer, so the write is either
///   discarded or, worse, lands after the commit snapshot and is silently lost.
///
/// Applied by all three handlers here. `join` and `enter_gate` deliberately accept
/// `FIGHTING` as well as `LOBBY`: late entry is the design's matchmaking (`00-game-design-
/// spec.md` §4 — "the lobby *is* the matchmaker"), all 20 seats exist before the crank is
/// armed so a late seat costs the frozen account list nothing (R15), and a raid that
/// refused reinforcements would punish exactly the player who watched the fight start.
fn assert_playable(phase: u8) -> Result<(), ProgramError> {
    if phase == PHASE_LOBBY || phase == PHASE_MUSTERING || phase == PHASE_FIGHTING {
        Ok(())
    } else {
        Err(HeartrotError::WrongPhase.into())
    }
}

