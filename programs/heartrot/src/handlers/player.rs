    #[test]
    fn geometry_holds() {
        // Every spawn is inside the map, on open floor, and unique per seat. The arena
        // side is `tick`'s point, checked here because this is where the wall test lives
        // and `tick` cannot see it: a spawn or a gate that lands a player inside the
        // generated dungeon leaves them unable to move at all, in any direction.
        let mut seen = [(0i16, 0i16); MAX_SEATS];
        for seat in 0..MAX_SEATS as u8 {
            for (x, y) in [
                lobby_spawn(seat),
                crate::handlers::tick::entrance_for(seat as usize),
            ] {
                assert!((0..=MAP_MAX_XY).contains(&x) && (0..=MAP_MAX_XY).contains(&y));
                assert!(!is_wall(x, y), "seat {seat} spawns in a wall");
            }
            let p = lobby_spawn(seat);
            assert!(!seen[..seat as usize].contains(&p), "seat {seat} stacks");
            seen[seat as usize] = p;
        }

        // The outer ring is closed.
        assert!(is_wall(0, 0) && is_wall(MAP_MAX_XY, MAP_MAX_XY));
        assert!(is_wall(500, MAP_MAX_XY) && is_wall(0, 500));
        // ...and it opens onto floor. Searched for rather than typed as tile (1, 1): the
        // perimeter's thickness is the map's to choose and it is two tiles today, so the
        // named-tile form of this line asserted the ring was *thin* while claiming to
        // assert it was closed. `inset` is the first open column of the boss's air and is
        // reused below, so the two assertions cannot disagree about where the ring ends.
        let inset = (0..MAP_TILES as i16)
            .find(|tx| !is_wall(tx * TILE, TILE))
            .expect("row 1 is solid — the boss's air must be open floor or every ray dies");
        assert!(inset > 0, "the border ring is open at the top-left corner");
        // Off-map fails closed rather than indexing out of range.
        assert!(is_wall(-1, 0) && is_wall(0, -1) && is_wall(MAP_MAX_XY + 1, 0));

        // The interior is a dungeon, not an empty rectangle. Stated as "somewhere below
        // the pit there is rock" rather than as a named tile: the named-tile version of
        // this assertion had to be rewritten the moment the grid was redrawn, which is
        // exactly the property a drift guard must not have. If `crate::map::WALLS` ever
        // regresses to a bare border ring, this fires.
        assert!(
            (1..MAP_TILES as i16 - 1)
                .any(|ty| (1..MAP_TILES as i16 - 1).any(|tx| is_wall(tx * TILE, ty * TILE))),
            "interior has no walls",
        );
        // The boss stands on floor. `map.rs` const-asserts the same thing at compile time
        // against `BOSS_SPAWN`; this reads it through `is_wall`, which is the function the
        // *player* is refused by, so the two indexing conventions are checked against each
        // other rather than each being checked against itself.
        assert!(
            !is_wall(crate::map::BOSS_SPAWN.0, crate::map::BOSS_SPAWN.1),
            "boss spawns in a wall",
        );

        // Walking into the ring is clamped in bounds and then rejected as wall, and
        // the clamp itself never overflows at the i16 extremes.
        for (dx, dy) in MOVE_STEP {
            let nx = i16::MAX.saturating_add(dx).clamp(0, MAP_MAX_XY);
            let ny = i16::MIN.saturating_add(dy).clamp(0, MAP_MAX_XY);
            assert!((0..=MAP_MAX_XY).contains(&nx) && (0..=MAP_MAX_XY).contains(&ny));
        }
        // West out of the first open column is rock, whatever the ring's thickness.
        assert!(is_wall(
            (inset * TILE).saturating_add(MOVE_STEP[6].0).clamp(0, MAP_MAX_XY),
            TILE
        ));

        // Diagonals cover the same ground as straights, within one unit.
        for (dx, dy) in MOVE_STEP {
            let d2 = (dx as i32) * (dx as i32) + (dy as i32) * (dy as i32);
            let straight = (STEP as i32) * (STEP as i32);
            assert!((d2 - straight).abs() <= 2 * STEP as i32);
        }

        // `octant` must agree with `MOVE_STEP` on all eight directions, or the chain
        // walks a player somewhere other than where the client predicted and every
        // move rubber-bands. Feeding each step vector back through the quantizer is
        // the round trip: sign-only, so magnitude cannot matter.
        for (dir, (dx, dy)) in MOVE_STEP.iter().enumerate() {
            assert_eq!(octant(dx.signum() as i8, dy.signum() as i8), Ok(dir as u8));
            // Any vector in the same sign quadrant resolves to the same step.
            let scaled = octant(
                (*dx as i32 * 7).signum() as i8,
                (*dy as i32 * 7).signum() as i8,
            );
            assert_eq!(scaled, Ok(dir as u8), "magnitude changed the direction");
        }
        // The `atan2` mapping in app/src/input/controls.ts, spot-checked: north is 0
        // (y grows *down*, so north is negative dy) and the octants run clockwise.
        assert_eq!(octant(0, -1), Ok(0));
        assert_eq!(octant(127, -127), Ok(1));
        assert_eq!(octant(i8::MIN, 0), Ok(6));
        // Standing still is not a direction.
        assert!(octant(0, 0).is_err());

        // Every gate is reachable: every unit of it is inside the map and on floor, the
        // block is closed on all four sides, and it names its own tier. One walled tile
        // inside a block is a gate a player can stand next to and never on, which is a
        // tier that cannot be picked and which nothing at runtime reports.
        assert_eq!(GATES.len(), N_TIERS);
        for (tier, gate) in GATES.iter().enumerate() {
            let tier = tier as u8;
            assert_eq!(gate_at(gate.min_x, gate.min_y), Some(tier));
            assert_eq!(gate_at(gate.max_x, gate.max_y), Some(tier));
            assert_eq!(gate_at(gate.min_x - 1, gate.min_y), None);
            assert_eq!(gate_at(gate.max_x + 1, gate.max_y), None);
            assert_eq!(gate_at(gate.min_x, gate.min_y - 1), None);
            assert_eq!(gate_at(gate.min_x, gate.max_y + 1), None);
            let mut gx = gate.min_x;
            while gx <= gate.max_x {
                let mut gy = gate.min_y;
                while gy <= gate.max_y {
                    assert!(
                        gate_at(gx, gy) == Some(tier) && !is_wall(gx, gy),
                        "gate {tier} unit ({gx}, {gy}) is wall"
                    );
                    gy += TILE;
                }
                gx += TILE;
            }
        }

        // No gate is the boss. `map.rs` const-asserts this too; it is repeated here
        // because the failure is silent and total — a gate block overlapping `BOSS_SPAWN`
        // would flip a player into the arena standing inside the shell.
        assert!(
            gate_at(crate::map::BOSS_SPAWN.0, crate::map::BOSS_SPAWN.1).is_none(),
            "a gate block contains BOSS_SPAWN",
        );
    }

    /// Check 11.6, and the reason `PIT_TOP` is a comparison rather than a row of wall
    /// tiles: for every pit column, a raider standing at the top of the pit is held there
    /// by the arena box **while the tile north of them is open floor**.
