/// Tag 16 — release a seat. The other half of `join`, and the reason a player who leaves
/// stops existing for everyone else.
///
/// WHY THIS INSTRUCTION EXISTS. There was no way to give a seat back. `join` was the only
/// writer of `session_pubkey`, and nothing but `Players::reset_for_incarnation` ever
/// cleared one — so a player who closed the tab stayed `occupied` and `ZONE_ARENA`
/// forever. Three consequences, all of them observed: the other raiders kept seeing a
/// motionless archer that could not be killed or removed; `arena_occupants` never fell, so
/// the wipe branch in `boss_tick` could not fire and the raid ran its full six minutes to
/// enrage; and the leaver could not rejoin, because their old seat still held their
/// identity in an arena that was no longer in the lobby.
///
/// **Administered, not self-served**, exactly like `join`: the payer must be
/// `Arena.crank_authority`. The Worker proves the caller's Privy identity before it sends
/// this, and passing that identity here is what stops the instruction being a way to kick
/// somebody else — the seat is only released if the identity on it matches.
///
/// Allowed in `LOBBY`, `MUSTERING` and `FIGHTING`, the three phases where a seat means
/// anything. Leaving mid-fight is the case that matters most, and it is the one the
/// wipe check needs: `arena_occupants` counts seats, so a raid everyone has left can only
/// end early once the seats are actually gone.
///
/// Idempotent. A seat already free, or holding a different identity, is `Ok(())` and not a
/// refusal — this arrives from a closing tab via `sendBeacon`, which retries nothing and
/// reports nothing, and a duplicate release must not become an error nobody will ever see.
pub fn leave_seat(program_id: &Address, accounts: &mut [AccountView], data: &[u8]) -> ProgramResult {
    let [arena_ai, players_ai, treasury_ai, ..] = accounts else {
        return Err(ProgramError::NotEnoughAccountKeys);
    };
    if data.len() != LEAVE_DATA_LEN {
        return Err(ProgramError::InvalidInstructionData);
    }
    let seat = data[0];
    if seat as usize >= MAX_SEATS {
        return Err(HeartrotError::SeatOutOfRange.into());
    }
    let mut identity = [0u8; 32];
    identity.copy_from_slice(&data[1..33]);

    validate_pair(program_id, arena_ai, players_ai, treasury_ai, true)?;
    let treasury_key = *treasury_ai.address();

    let mut arena_data = arena_ai.try_borrow_mut()?;
    let arena = state::load_mut::<Arena>(&mut arena_data)?;
    assert_playable(arena.phase)?;
    if treasury_key.as_ref() != arena.crank_authority.as_slice() {
        return Err(HeartrotError::NotArenaAuthority.into());
    }

    let mut players_data = players_ai.try_borrow_mut()?;
    let players = state::load_mut::<Players>(&mut players_data)?;
    let Some(slot) = players.slots.get_mut(seat as usize) else {
        return Err(HeartrotError::SeatOutOfRange.into());
    };

    // Already gone, or never theirs. Both are `Ok`: see the idempotency note above.
    if slot.session_pubkey == UNCLAIMED || slot.identity != identity {
        return Ok(());
    }

    release_seat(arena, slot, seat);
    Ok(())
}

/// The release itself, once the seat is proven the caller's: the whole slot, and both
/// arena counts a seat is part of.
///
/// The whole slot, not just the key. A half-cleared seat is the defect this file has
/// paid for twice: `seat_occupied` is a cache of `session_pubkey != 0`, and position,
/// HP, class and damage all have to go with it or the next player to take this seat
/// inherits a stranger's corpse.
///
/// And `alive_count`, which `enter_gate` added this seat to and which nothing but the
/// FIGHTING tick's recount (`tick.rs`, step 5) ever takes a seat out of. LOBBY and
/// MUSTERING have no recount, so a raider who walked HARD and pressed Exit before the
/// crank woke left the count at 1 over an empty pit, and [`locked_tier`] read that as a
/// raid on HARD: every next raider refused `WrongGate` on the other two gates, and
/// `begin_muster` refused `NoRaiders` on the one they were allowed. A seat the tick has
/// already dropped (`hp == 0`, dead for the raid) is not subtracted twice; mid-fight the
/// recount lands within one tick either way, so this only has to agree with it.
fn release_seat(arena: &mut Arena, slot: &mut PlayerSlot, seat: u8) {
    if slot.zone == ZONE_ARENA && slot.hp != 0 {
        arena.alive_count = arena.alive_count.saturating_sub(1);
    }
    *slot = PlayerSlot::zeroed();
    arena.seat_occupied &= !(1u32 << seat);
}

/// `enter_gate(seat)` — accounts `[arena (w), players (w), session key (signer)]`.
///
/// Flips the seat from lobby to arena and teleports it to the arena entrance. The gate it
/// stood in is the raid's difficulty: the first raider through writes `arena.difficulty`
/// from it, and everyone after them must walk the same one ([`gate_refusal`]).
///
/// The only player-callable handler here with no tick counter, and it does not need one:
/// the `zone != ZONE_LOBBY` refusal below makes it one-shot per seat per incarnation, so a
/// flood of repeats is a flood of rejections that write nothing — where `move` and `shoot`
/// would each succeed, every time, at zero fee. That refusal is therefore load-bearing
/// twice over: it is the rate limit *and* the `alive_count` bound.
pub fn enter_gate(
    program_id: &Address,
    accounts: &mut [AccountView],
    data: &[u8],
) -> ProgramResult {
    let [arena_ai, players_ai, authority_ai, ..] = accounts else {
        return Err(ProgramError::NotEnoughAccountKeys);
    };

    // Tag 5 is not in `lib.rs::ZERO_ARG_TAGS`, so a trailing payload reaches this
    // handler and this is the only place that can refuse it. One argument byte, exactly.
    let &[seat] = data else {
        return Err(ProgramError::InvalidInstructionData);
    };

    validate_pair(program_id, arena_ai, players_ai, authority_ai, true)?;

    let mut arena_data = arena_ai.try_borrow_mut()?;
    let arena = state::load_mut::<Arena>(&mut arena_data)?;
    assert_playable(arena.phase)?;

    let mut players_data = players_ai.try_borrow_mut()?;
    let players = state::load_mut::<Players>(&mut players_data)?;
    let seat = seat as usize;
    // Same perimeter as `move_player`: the index is bounds-checked, the signature is
    // what proves the caller owns the seat.
    let slot = players
        .slots
        .get_mut(seat)
        .ok_or(HeartrotError::SeatOutOfRange)?;
    assert_session_authority(slot, authority_ai)?;

    let locked = locked_tier(arena);
    let tier = gate_refusal(slot, locked)?;
    // The first raider through picks the boss for everyone: `difficulty` is written here
    // and nowhere else, once per incarnation, and `begin_next_incarnation` clears it. It
    // is written before the seat flips so the two facts land in one transaction — a seat
    // in `ZONE_ARENA` under an arena still reading EASY would be the raid tuned wrong for
    // exactly the tick the crank sizes the core in.
    if locked.is_none() {
        arena.difficulty = tier;
    }

    // `boss_tick` owns the arena entrance; a second definition here would read as a
    // teleport bug the first time anyone died. It is also inside the arena box by
    // construction — every `E` mark is a `P` tile — so the flip below cannot strand the
    // seat outside the only y range `move_player` will accept.
    let (x, y) = crate::handlers::tick::entrance_for(seat);
    slot.zone = ZONE_ARENA;
    slot.x = x;
    slot.y = y;
    // A bare octant, like every `facing` write outside `shoot`: it also clears the
    // charged-shot flag, so nobody walks into the pit with a charged arrow drawn.
    slot.facing = 0;
    slot.hp = slot.hp_max;
    slot.respawn_at_tick = 0;

    // Cap rather than wrap: `alive_count` drives `bullets_per_volley = 3 + alive_count`,
    // and a wrapped count would fill the pool on the next volley.
    arena.alive_count = arena.alive_count.saturating_add(1).min(MAX_SEATS as u8);
    Ok(())
}

