/// Arena-space units per map tile (positions are sub-tile so bullets, whose velocity is
/// an i8, have somewhere to move between ticks; tile indices are `pos / TILE`), and the
/// map edge in tiles — 64, which is exactly one `u64` of wall bits per row.
///
/// Both are re-exported from [`crate::map`] rather than declared a second time here.
/// That module is generated by `tools/gen_map.py` from `assets/map/arena.json` together
/// with the `WALLS` bitboard they size, so the numbers this file indexes with are the
/// numbers the map was compiled from — by construction, not by two copies someone has
/// to keep equal. (`map.rs`'s `const _: () = assert!(TILE == player::TILE)` drift guards
/// still hold; they now compare the re-export against its own definition.)
pub use crate::map::{MAP_TILES, TILE};

/// Highest legal coordinate. Everything written to `x`/`y` is clamped into
/// `0..=MAP_MAX_XY`, which is also what makes the tile index below in-range.
pub const MAP_MAX_XY: i16 = (MAP_TILES as i16) * TILE - 1;

// The gate block (`GATE_MIN_X`..=`GATE_MAX_Y`) and the pit box (`PIT_TOP`/`PIT_BOT`) are
// imported from `crate::map`, not declared here.
//
// They used to be six literals in this file, and `tools/gen_map.py` parsed them back out
// of this source to check the grid it had just emitted — one fact stored twice, in the
// two places least able to notice they had drifted. They are `G` and `P` marks in
// `assets/map/arena.json` now, so the tiles `enter_gate` accepts are the tiles the map
// was compiled from, and `map.rs`'s const-assert block can prove `BOSS_SPAWN` is outside
// the gate on every `cargo check`.
//
// Standing inside the gate block is what `enter_gate` requires — the lobby *is* the
// matchmaker, so the gate has to be a place you walk to and not an API call you make from
// across the map.

/// The lobby entrance and the sideways pitch seats fan out along, so twenty players
/// never stack on one pixel and the client can render a join without waiting for the
/// next crank tick to separate them.
///
/// The *arena* entrance is deliberately not here: `tick::entrance_for` owns it, because
/// that is where `boss_tick` returns a dead player, and walking through the gate has to
/// land in the same place a respawn does.
const LOBBY_ENTRANCE: (i16, i16) = (28 * TILE, 52 * TILE);
const LOBBY_SPACING: i16 = 24;

/// Starting health. Balance number, not a layout number — `hp_max` is per-slot state
/// so an incarnation could scale it later without touching this file.
pub const PLAYER_HP_MAX: u16 = 100;

/// Eight-way step, indexed by `facing`: 0 N, 1 NE, 2 E, 3 SE, 4 S, 5 SW, 6 W, 7 NW,
/// with y increasing downward. The diagonal component is `round(TILE / √2)` so a
/// diagonal move covers the same ground as a straight one — computed here as a
/// constant because the program may never touch a float.
const STEP: i16 = TILE;
const STEP_DIAG: i16 = 11;
const MOVE_STEP: [(i16, i16); 8] = [
    (0, -STEP),
    (STEP_DIAG, -STEP_DIAG),
    (STEP, 0),
    (STEP_DIAG, STEP_DIAG),
    (0, STEP),
    (-STEP_DIAG, STEP_DIAG),
    (-STEP, 0),
    (-STEP_DIAG, -STEP_DIAG),
];

/// `PlayerSlot.session_pubkey` sentinel for "seat never claimed".
const UNCLAIMED: [u8; 32] = [0u8; 32];

/// Tag 4 argument block: `seat` u8 `[0]`, `skin_id` u8 `[1]`, `session_pubkey` `[2..34]`,
/// `identity` `[34..66]`, `class` u8 `[66]`. This slicing *is* the frozen ABI —
/// `instruction.rs` and `docs/architecture/05-wire-abi.md` describe it, and TypeScript
/// conforms to it. When a client disagrees, the client is what changes.
///
/// `class` is **appended**, not packed beside `skin_id`, so no existing offset moves and
/// both 32-byte slices are untouched (`17-fullscreen-spec.md` §5.4). The only thing a
/// client built against the 66-byte block gets wrong is the length, which is a clean
/// `InvalidInstructionData` here rather than a misread byte somewhere downstream. That
/// makes the program, the app and the Worker one indivisible deploy, deliberately.
const JOIN_DATA_LEN: usize = 1 + 1 + 32 + 32 + 1;

