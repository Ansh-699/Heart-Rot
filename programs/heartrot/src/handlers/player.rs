/// Where seat *n* appears when it joins the lobby: fanned out sideways from the
/// entrance, the same shape `tick::entrance_for` uses on the arena side.
pub fn lobby_spawn(seat: u8) -> (i16, i16) {
    let offset = (seat as i16)
        .saturating_sub(MAX_SEATS as i16 / 2)
        .saturating_mul(LOBBY_SPACING);
    (
        LOBBY_ENTRANCE.0.saturating_add(offset).clamp(0, MAP_MAX_XY),
        LOBBY_ENTRANCE.1.clamp(0, MAP_MAX_XY),
    )
}

/// Write a freshly claimed seat, in place.
///
/// **Zero first, then set the fields whose correct value is not zero.** The ordering is the
/// whole point: assigning the slot field by field is `PlayerSlot`'s field list stored a
/// second time, here, and the second copy is the one that goes stale. It already had —
/// `deaths` was claimed out of `PlayerSlot._pad1` this run, and a field-by-field claim would
/// have carried a previous occupant's death count onto a re-used seat while looking
/// complete. `..PlayerSlot::zeroed()` makes that unrepresentable: a field added to the slot
/// is zero here until someone deliberately names it.
///
/// It is also exactly what [`Players::reset_for_incarnation`] does to all twenty seats, so a
/// seat claimed after a new incarnation and a seat claimed on a fresh arena are the same
/// bytes.
///
/// Every field left implicit is correct at zero: `facing` 0 is north, `last_move_seq` 0 is
/// "no input yet", `respawn_at_tick` is reserved and always 0, `damage_dealt` and
/// `deaths` start a leaderboard row at nothing, and both
/// rate-limit stamps start at 0 — legal under the `!=` rule in [`move_clock`], which can
/// only collide in the one slot/tick where the clock also reads 0.
fn claim_seat(
    slot: &mut PlayerSlot,
    seat: u8,
    skin_id: u8,
    class: u8,
    session_pubkey: [u8; 32],
    identity: [u8; 32],
) -> Result<(), ProgramError> {
    let (x, y) = lobby_spawn(seat);
    *slot = PlayerSlot {
        zone: ZONE_LOBBY,
        skin_id,
        x,
        y,
        hp: PLAYER_HP_MAX,
        hp_max: PLAYER_HP_MAX,
        session_pubkey,
        identity,
        ..PlayerSlot::zeroed()
    };
    // The class is written through `PlayerSlot::set_class` rather than by masking the byte
    // here, because that byte is shared with the aim `shoot::fire` writes and one encoder
    // is the only way the two halves cannot be typed differently in two files. On a slot
    // that was just zeroed the aim it preserves is 0, which is what a seat that has fired
    // no shot should carry.
    slot.set_class(class)
}

/// Is the tile containing this point solid? Anything off the map counts as wall, so
/// a caller that skips the clamp fails closed rather than indexing out of range.
fn is_wall(x: i16, y: i16) -> bool {
    if x < 0 || y < 0 {
        return true;
    }
    let tx = (x / TILE) as usize;
    let ty = (y / TILE) as usize;
    if tx >= MAP_TILES {
        return true;
    }
    match WALLS.get(ty) {
        Some(row) => row & (1u64 << tx) != 0,
        None => true,
    }
}

/// The y range a seat in `zone` may stand in. The *second* kind of barrier in this
/// program, and the one that is not made of tiles.
///
/// A raider is held inside `PIT_TOP..=PIT_BOT` by two comparisons rather than by wall
/// tiles, because the rows above the pit cannot be wall: `shoot::raycast` tests `is_wall`
/// before the part rectangles, so one solid tile between a player and the boss kills every
/// shot in that column. The pit ceiling is a movement rule laid over open floor.
///
/// - `PIT_TOP` is the dais's crest. Since the pit became the whole dais it is the coarse
///   half of the raider's rule; the fine half -- the dais tile by tile, and the boss's
///   body -- is [`standable`], and it is what actually keeps a raider off the air beside
///   the dais's shoulders and out of the creature.
/// - `PIT_BOT` stops a raider retreating down the gate corridor. Not tidiness:
///   `tick::spawn_volley` aims at the nearest live player, so one camper at the corridor
///   mouth makes the boss spend every volley on a target the rim shields.
///
/// **The two boxes tile the map at the gate seam and neither zone is unbounded.** The
/// lobby used to be — `zone != ZONE_ARENA` short-circuited the whole test — on the
/// argument that the lobby half is bounded by real walls. It is not: rows 1..23 are
/// deliberately open floor so `raycast` survives, so a `ZONE_LOBBY` seat could walk out of
/// the temple, up the pit and stand inside the boss's crown (measured: 445,696 reachable
/// positions, minimum y = 16, tile row 1). Such a seat is invisible to every mechanic —
/// not in `live`, never targeted, unslammable, cannot shoot — and every client draws it
/// standing in the creature. The lobby box is therefore `PIT_BOT + 1 ..= MAP_MAX_XY`:
/// everything below the rim, which is the whole lobby half and the gate.
///
/// The seam is exactly one unit wide and every gate block sits below it (`map.rs`
/// const-asserts `min_y > PIT_BOT`), which is what makes the flip safe in both directions:
/// the doorway rows are inside the *lobby* box, the entrance rows are inside the *arena*
/// box, and `enter_gate` teleports across the seam rather than stepping over it. If the
/// two boxes left a gap, a player who flipped zone standing on the gate tiles would be
/// outside the only legal y range with no legal move in any direction — a hard freeze
/// with no error anywhere.
fn zone_box(zone: u8) -> (i16, i16) {
    if zone == ZONE_ARENA {
        (PIT_TOP, PIT_BOT)
    } else {
        (PIT_BOT + 1, MAP_MAX_XY)
    }
}

/// How far outside its box a seat in `zone` standing at `y` is; 0 when it is inside.
///
/// `saturating_sub` because a corrupt or stale `y` is a caller's byte, not a panic: every
/// write clamps into `0..=MAP_MAX_XY`, but this program runs with `overflow-checks = true`
/// and an abort has no error code to read.
fn box_overshoot(zone: u8, y: i16) -> i16 {
    let (top, bot) = zone_box(zone);
    top.saturating_sub(y).max(y.saturating_sub(bot)).max(0)
}

/// May a seat in `zone` step from `y` to `ny`? The destination must be inside the zone's
/// box — **or** strictly closer to it than where the seat already stands.
///
/// That second clause is the un-stranding rule, and it is why this is not a bare range
/// test. Narrowing a box under a live account (which this fix does: yesterday's program
/// let a lobby seat stand at y = 16) leaves seats outside the box that were legal when
/// they were written, and a bare destination test freezes every one of them — no direction
/// helps, including the one pointing home, because a sideways step keeps the same illegal
/// y. Trading the freeze for a bounded walk back is strictly better: the overshoot is a
/// non-negative integer that must *decrease* every step, so the escape terminates inside
/// the box and cannot be ridden in the other direction.
fn may_move_to(zone: u8, y: i16, ny: i16) -> bool {
    // A stranded seat is governed by walls ALONE until it re-enters its box.
    //
    // The strictly-decreasing-overshoot rule this replaces could not be satisfied at every
    // stranded position: `move_player` demands `!is_wall(nx, ny) && may_move_to(..)`, and a
    // replay of both predicates over the generated `WALLS` found 4,620 stale lobby positions
    // where no step is both non-wall and overshoot-decreasing. Those seats froze on their
    // first move attempt, with no error to distinguish it from a wall.
    //
    // Letting a stranded seat move freely cannot freeze anyone that walls alone do not,
    // because it is exactly the rule the previous program applied to these seats — the one
    // that let them stand here. It is one-way in the direction that matters: `box_overshoot`
    // is 0 everywhere inside the box, so once a seat is home `over(ny) == 0` is the only
    // clause that can hold and it can never step back out.
    box_overshoot(zone, y) > 0 || box_overshoot(zone, ny) == 0
}

/// May a raider stand on the tile containing this point? `crate::map::DAIS`, the drawn
/// dais, indexed exactly as [`is_wall`] indexes `WALLS` -- and off-map answers *no*, the
/// same fail-closed direction.
fn on_dais(x: i16, y: i16) -> bool {
    if x < 0 || y < 0 {
        return false;
    }
    let tx = (x / TILE) as usize;
    let ty = (y / TILE) as usize;
    if tx >= MAP_TILES {
        return false;
    }
    match DAIS.get(ty) {
        Some(row) => row & (1u64 << tx) != 0,
        None => false,
    }
}

/// Where a seat in `zone` may stand, beyond what [`zone_box`] says: a raider on the dais
/// and outside the boss's body; a lobby seat anywhere -- walls and the band are its whole
/// rule, as they always were.
///
/// The *third* kind of barrier, and the one that let the pit become the whole dais. The
/// raid used to be held below the creature's feet line by `PIT_TOP` alone, and the player
/// asked to walk the circle instead. Two things then have to refuse a step that no wall
/// can: the air beside the dais's shoulders (floor to a ray, because the dais narrows
/// upward and a wall over a shoulder tile is a stand from which every upward shot dies --
/// `map::DAIS` explains) and the boss's own body (`crate::body`, the hitbox table folded,
/// because a wall under the boss kills every ray in its columns).
fn standable(zone: u8, x: i16, y: i16) -> bool {
    zone != ZONE_ARENA || (on_dais(x, y) && !in_body(x, y))
}

/// May a seat in `zone` step from `(x, y)` to `(nx, ny)`, as far as [`standable`] is
/// concerned? The destination must be standable -- **or** the seat already is not.
///
/// The same shape as [`may_move_to`], for the same reason: this rule was laid under live
/// accounts. The old pit's kerb fill made two tiles pit that the drawn dais does not cover,
/// and a raider standing on one of them when the program was swapped is off the dais
/// through no fault of their own; a bare destination test would freeze them there. Walls
/// alone govern such a seat until it steps onto a standable unit, and from then on the
/// only clause that can hold is the destination's, so it can never step back out.
fn may_stand_step(zone: u8, (x, y): (i16, i16), (nx, ny): (i16, i16)) -> bool {
    !standable(zone, x, y) || standable(zone, nx, ny)
}

/// The tier this raid is already committed to, or `None` while nobody has opened it.
///
/// A raid is opened by its first raider: `raid_size` is 0 until the first FIGHTING tick
/// counts the pit and `alive_count` is 0 until the first `enter_gate` — both zeroed by
/// `Arena::begin_next_incarnation`, the only road back to `PHASE_LOBBY`. Either non-zero
/// means someone has walked a gate this incarnation, and `difficulty` is the gate they
/// walked. Read here and written in [`enter_gate`] off this one predicate, so "first
/// raider" cannot mean one thing to the refusal and another to the write.
fn locked_tier(arena: &Arena) -> Option<u8> {
    if arena.raid_size == 0 && arena.alive_count == 0 {
        None
    } else {
        Some(arena.difficulty)
    }
}

/// The four refusals `enter_gate` owes a caller, as a pure function of the seat and the
/// raid's tier, answering the tier of the gate the seat stands in.
///
/// Split out of the handler so the gate's rules are testable without an `AccountView`:
/// this *is* the "one-way, on a gate, the raid's gate, and only a real seat" contract,
/// and every one of the four is load-bearing (see [`enter_gate`]).
fn gate_refusal(slot: &PlayerSlot, locked: Option<u8>) -> Result<u8, ProgramError> {
    // One direction only. Coming back out is `phase == Settled`, not an instruction —
    // and rejecting the repeat is what keeps `alive_count` from being incremented
    // twice by one player, which would inflate `bullets_per_volley` for everyone. It is
    // also the rate limit: `enter_gate` has no tick counter and needs none, because a
    // flood of repeats is a flood of rejections that write nothing.
    if slot.zone != ZONE_LOBBY {
        return Err(HeartrotError::WrongZone.into());
    }
    // The client retries this instruction while the player walks onto the tile, so
    // "not there yet" must be tellable apart from every other gate failure.
    let Some(tier) = gate_at(slot.x, slot.y) else {
        return Err(HeartrotError::NotOnGate.into());
    };
    // The raid fights ONE boss, tuned by the gate its first raider chose. A later raider on
    // another doorway is refused with a code the client does not retry on: standing still
    // never heals this one, walking to the named gate does.
    if let Some(locked) = locked {
        if tier != locked {
            return Err(HeartrotError::WrongGate.into());
        }
    }
    // Aliveness is derived as `hp != 0 && zone == ZONE_ARENA`, so a seat with a zero
    // `hp_max` would count toward `alive_count` while never being alive. `join`
    // always sets it; this is the assertion that says so.
    if slot.hp_max == 0 {
        return Err(ProgramError::InvalidAccountData);
    }
    Ok(tier)
}

