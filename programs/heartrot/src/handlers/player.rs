    /// Finding 2 of `docs/review/chain.md`, stated as the search the review ran: exhaustive
    /// BFS over every unit position a `ZONE_LOBBY` seat can reach through the shipped
    /// `map::WALLS` with the shipped eight-way `MOVE_STEP`, under the real move rule.
    ///
    /// Before the lobby box existed this search reached 445,696 positions with minimum
    /// y = **16** — tile row 1, inside the boss's crown — because the rows above the pit
    /// are deliberately open floor (see [`the_pit_ceiling_holds_raiders_without_being_a_wall`])
    /// and the clamp only applied to `ZONE_ARENA`. Two properties are asserted together
    /// because either alone is satisfiable by a broken rule: nothing above the rim is
    /// reachable, **and** the gate is still reachable from all twenty lobby spawns. A box
    /// that boxed the lobby in would pass the first and fail the second, and that failure
    /// is a raid nobody can ever start.
    ///
    /// Searched from one seat's spawn, once instead of twenty times, and the other
    /// nineteen spawns are asserted to be *in* the result: inside the legal set the step
    /// relation is symmetric (`MOVE_STEP` contains every negation, and the clamp is
    /// unreachable because the border ring is wall), so "seat 0 reaches seat k's spawn and
    /// the gate" is "seat k reaches the gate".
    ///
    /// Seeding this from a gate unit instead is what a first draft did, and it failed:
    /// `(x + y)` is even for every step in `MOVE_STEP` (±16 cardinal, ±11 diagonal), so
    /// its parity is invariant and the map's unit positions are two lattices that never
    /// touch. `(480, 639)` is on the odd one and no spawn is. Starting from a real spawn
    /// is the only seed that asks the question a player asks.
    #[test]
    fn a_lobby_seat_cannot_reach_the_pit_or_the_bosss_air() {
        let span = (MAP_MAX_XY as usize) + 1;
        let idx = |x: i16, y: i16| (y as usize) * span + (x as usize);
        let mut seen = vec![false; span * span];
        let start = lobby_spawn(0);
        seen[idx(start.0, start.1)] = true;
        let mut queue = std::collections::VecDeque::from([start]);
        let (mut count, mut min_y, mut gate_units) = (0usize, MAP_MAX_XY, [0usize; N_TIERS]);

        while let Some((x, y)) = queue.pop_front() {
            count += 1;
            min_y = min_y.min(y);
            if let Some(tier) = gate_at(x, y) {
                gate_units[tier as usize] += 1;
            }
            for (dx, dy) in MOVE_STEP {
                let nx = x.saturating_add(dx).clamp(0, MAP_MAX_XY);
                let ny = y.saturating_add(dy).clamp(0, MAP_MAX_XY);
                // Verbatim the refusals in `move_player`.
                if is_wall(nx, ny)
                    || !may_move_to(ZONE_LOBBY, y, ny)
                    || !may_stand_step(ZONE_LOBBY, (x, y), (nx, ny))
                {
                    continue;
                }
                if !seen[idx(nx, ny)] {
                    seen[idx(nx, ny)] = true;
                    queue.push_back((nx, ny));
                }
            }
        }

        assert!(
            min_y > PIT_BOT,
            "a lobby seat reaches y={min_y}, above the rim at {PIT_BOT} — row \
             {} is inside the boss",
            min_y / TILE,
        );
        assert!(!seen[idx(crate::map::BOSS_SPAWN.0, crate::map::BOSS_SPAWN.1)]);
        // The escape clause cannot be ridden upward: every reachable position is inside
        // the box, so the walk that produced them never left it.
        // 155,648 positions today, against 445,696 before the lobby box existed. It was
        // 170,240 while the lobby was a pillared temple: the open arena deletes 26 pillars
        // but hands the deeper pit three rows and the perimeter a second tile, and the rows
        // cost more than the pillars returned. The bound is loose on purpose — the exact
        // number is a property of the generated map and would have to be re-measured every
        // time `arena.json` is redrawn — but a lobby that has collapsed to a corridor is a
        // different bug wearing this one's clothes.
        assert!(
            count > 10_000,
            "only {count} positions reachable — the lobby is a closet"
        );

        // The other half of the property, and the one a too-tight box breaks: every gate
        // is still there to be walked onto, from every seat's spawn — a tier no spawn can
        // reach is a difficulty nobody can pick.
        for (tier, units) in gate_units.iter().enumerate() {
            assert!(
                *units > 0,
                "no unit of gate {tier} is reachable from a lobby spawn"
            );
        }
        for seat in 0..MAX_SEATS as u8 {
            let (x, y) = lobby_spawn(seat);
            assert!(
                seen[idx(x, y)],
                "seat {seat} spawns at ({x}, {y}), which seat 0 cannot reach — so seat \
                 {seat} cannot reach the gate seat 0 can",
            );
        }
    }

    /// The freeze this fix is most likely to cause, asserted rather than argued: a seat
    /// that has just crossed the gate seam — in either direction — has somewhere to go.
    ///
    /// Phase is in the loop because it is the other half of "can this seat act": movement
    /// geometry does not read the phase, and asserting that here is what would catch a
    /// future phase gate that made the muster or the fight unwalkable. A raider who
    /// entered during `MUSTERING` and could not move until `FIGHTING` would be a twenty-
    /// second freeze with no error, which is the same bug wearing a clock.
    #[test]
    fn a_seat_that_just_crossed_the_gate_can_always_move() {
        let step_exists = |zone: u8, x: i16, y: i16| {
            MOVE_STEP.iter().any(|(dx, dy)| {
                let nx = x.saturating_add(*dx).clamp(0, MAP_MAX_XY);
                let ny = y.saturating_add(*dy).clamp(0, MAP_MAX_XY);
                !is_wall(nx, ny)
                    && may_move_to(zone, y, ny)
                    && may_stand_step(zone, (x, y), (nx, ny))
            })
        };

        for phase in [PHASE_LOBBY, PHASE_MUSTERING, PHASE_FIGHTING] {
            assert!(assert_playable(phase).is_ok());

            // Through the gate: `enter_gate` writes `ZONE_ARENA` and `entrance_for` in one
            // instruction, so this is the seat's state on the very next `move`.
            for seat in 0..MAX_SEATS {
                let (x, y) = crate::handlers::tick::entrance_for(seat);
                assert!(
                    step_exists(ZONE_ARENA, x, y),
                    "seat {seat} enters at ({x}, {y}) in phase {phase} with no legal move",
                );
            }

            // Standing on a gate and not yet through it: still `ZONE_LOBBY`, on rows the
            // *arena* box excludes. The client retries `enter_gate` from here, so a seat
            // can sit on these tiles for many slots — or, refused `WrongGate`, for as long
            // as it likes.
            for gate in GATES {
                let mut gx = gate.min_x;
                while gx <= gate.max_x {
                    let mut gy = gate.min_y;
                    while gy <= gate.max_y {
                        assert!(
                            step_exists(ZONE_LOBBY, gx, gy),
                            "a lobby seat on gate unit ({gx}, {gy}) is frozen in phase {phase}",
                        );
                        gy += TILE;
                    }
                    gx += TILE;
                }
            }
        }
    }

    /// The un-stranding rule, which exists for accounts the *old* program wrote: a lobby
    /// seat parked above the rim (legal yesterday, reachable only through finding 2) is
    /// governed by walls alone until it gets home, and is sealed in once it does.
    ///
    /// The earlier form of this rule permitted only strictly-overshoot-decreasing steps.
    /// That reads as "walk home and nowhere else", but `move_player` requires
    /// `!is_wall(nx, ny) && may_move_to(..)`, so at any position where every
    /// overshoot-decreasing step is a wall the seat had no legal move at all — a hard
    /// freeze, indistinguishable from a wall, for 4,620 stale lobby positions.
    #[test]
    fn a_stranded_seat_is_never_frozen_by_the_box() {
        // Deep in the boss's air, where the BFS above says the old program allowed.
        let stranded = 16i16;
        assert!(
            box_overshoot(ZONE_LOBBY, stranded) > 0,
            "the worst case really is stranded"
        );

        // The box refuses NOTHING while stranded, in any direction. This is the property
        // that makes a freeze unrepresentable: whatever `is_wall` permits, the box permits
        // too, so the box can never be the reason a seat has no move.
        for ny in [
            stranded,
            stranded + STEP,
            stranded + STEP_DIAG,
            stranded - STEP,
            stranded - STEP_DIAG,
        ] {
            assert!(
                may_move_to(ZONE_LOBBY, stranded, ny),
                "the box must refuse nothing at {ny}"
            );
        }

        // Walking home still terminates, and terminates inside the box rather than one
        // step short of it.
        let mut y = stranded;
        let mut steps = 0;
        while box_overshoot(ZONE_LOBBY, y) > 0 {
            assert!(may_move_to(ZONE_LOBBY, y, y + STEP));
            y += STEP;
            steps += 1;
            assert!(steps < MAP_TILES * 2, "the escape does not terminate");
        }
        assert!(y > PIT_BOT && y <= MAP_MAX_XY);

        // And it is not a hole in the ceiling. Once inside, the box is closed again in
        // both directions, from both zones — the seat cannot ride the escape back out.
        assert!(!may_move_to(ZONE_LOBBY, y, PIT_BOT));
        assert!(!may_move_to(ZONE_ARENA, PIT_TOP, PIT_TOP - 1));
        // From INSIDE, both ways. (`PIT_TOP - STEP` is itself outside the arena box, so a
        // seat standing there is stranded and moves freely by design — asserting a refusal
        // there would be asserting the rule this test exists to replace.)
        assert!(!may_move_to(ZONE_ARENA, PIT_TOP + STEP, PIT_TOP - 1));
        assert!(!may_move_to(ZONE_ARENA, PIT_BOT, PIT_BOT + 1));
    }

    /// Neither the box nor the dais nor the body may ever be the reason a seat has no
    /// move: over every position on the map, in both zones, the three together permit at
    /// least as many steps as `is_wall` does.
    ///
    /// Exhaustive rather than sampled, because the defect this replaces was found by replay
    /// and missed by a test that checked the y arithmetic without consulting the map. The
    /// generator sweeps the box and the dais the same way; the body is a hitbox fact it
    /// cannot see, so this is the only sweep that includes it.
    ///
    /// `walls_allow` is asserted true as well as equal, and that second assertion is not
    /// redundant: the equality alone is satisfied by `false == false`, which is a walkable
    /// tile with eight walled neighbours — a sealed pocket in the drawn map, and a freeze
    /// the box is innocent of. Nothing else in the repo would report one. (0 such tiles on
    /// this map, in both rooms.)
    #[test]
    fn the_box_never_removes_a_seats_last_legal_move() {
        for zone in [ZONE_LOBBY, ZONE_ARENA] {
            let mut y = 0i16;
            while y <= MAP_MAX_XY {
                let mut x = 0i16;
                while x <= MAP_MAX_XY {
                    if !is_wall(x, y) {
                        let walls_allow = MOVE_STEP.iter().any(|(dx, dy)| !is_wall(x + dx, y + dy));
                        let all_allow = MOVE_STEP.iter().any(|(dx, dy)| {
                            !is_wall(x + dx, y + dy)
                                && may_move_to(zone, y, y + dy)
                                && may_stand_step(zone, (x, y), (x + dx, y + dy))
                        });
                        assert!(
                            walls_allow,
                            "({x},{y}) is walkable floor sealed in on all eight sides"
                        );
                        assert_eq!(
                            walls_allow, all_allow,
                            "zone {zone} at ({x},{y}): the box, the dais or the body removed the last legal move"
                        );
                    }
                    x += TILE;
                }
                y += TILE;
            }
        }
    }

    /// The boss's body is a barrier and nothing else is: a raider walks up to the feet
    /// line and along it, is refused the step into the creature, and is refused it from
    /// beside the body too. Every place the program puts a raider -- the four doors and all
    /// twenty entrance ranks -- is outside it, or that seat would be born inside the boss
    /// and governed by walls alone until it walked out.
    ///
    /// The body's extent is the folded hitbox table and the boss stands at `BOSS_SPAWN`,
    /// so every position here is derived from those two rather than typed: redraw the
    /// creature, re-run the generator, and the test moves with it.
    #[test]
    fn the_boss_body_refuses_a_step_into_it_and_nothing_beside_it() {
        use crate::body::BOSS_BODY;
        let (bx, by) = crate::map::BOSS_SPAWN;
        let left = bx + BOSS_BODY.x as i16;
        let bottom = by + BOSS_BODY.y as i16 + BOSS_BODY.h as i16;

        // The feet line is the boss's own tile and it is outside the body: the hitboxes
        // end above it, so a raider can stand where the creature stands. From there, north
        // is into the body and refused; south and along the line are dais and accepted.
        assert!(bottom <= by, "a hitbox reaches below the feet line -- the boss tile is inside the body");
        assert!(standable(ZONE_ARENA, bx, by), "the feet line is not a stand");
        assert!(!may_stand_step(ZONE_ARENA, (bx, by), (bx, by - STEP)), "north into the body");
        assert!(!may_stand_step(ZONE_ARENA, (bx, by), (bx + STEP_DIAG, by - STEP_DIAG)));
        assert!(may_stand_step(ZONE_ARENA, (bx, by), (bx, by + STEP)), "south along the dais");
        assert!(may_stand_step(ZONE_ARENA, (bx, by), (bx + STEP, by)), "east along the feet line");
        assert!(may_stand_step(ZONE_ARENA, (bx, by), (bx - STEP, by)), "west along the feet line");

        // From beside the body, on the dais, one step east is inside it. `left` is the
        // first unit of body, so `left - 1` is the last unit of floor beside it -- searched
        // for a row where that floor is dais, which the drawn shoulders guarantee exists.
        let beside_y = (0..=MAP_MAX_XY)
            .step_by(TILE as usize)
            .find(|&y| standable(ZONE_ARENA, left - 1, y) && in_body(left - 1 + STEP, y))
            .expect("no dais unit beside the body");
        assert!(!may_stand_step(ZONE_ARENA, (left - 1, beside_y), (left - 1 + STEP, beside_y)));
        assert!(may_stand_step(ZONE_ARENA, (left - 1, beside_y), (left - 1, beside_y + STEP)));

        // A seat inside the body -- none is born there, asserted next, but the rule is
        // shaped so that one could never freeze -- moves under walls alone, out or deeper.
        assert!(may_stand_step(ZONE_ARENA, (bx, by - STEP), (bx, by)));
        assert!(may_stand_step(ZONE_ARENA, (bx, by - STEP), (bx, by - 2 * STEP)));

        for (x, y) in crate::map::ENTRANCES {
            assert!(standable(ZONE_ARENA, x, y), "door ({x}, {y}) is inside the boss or off the dais");
        }
        for seat in 0..MAX_SEATS {
            let (x, y) = crate::handlers::tick::entrance_for(seat);
            assert!(standable(ZONE_ARENA, x, y), "seat {seat} enters at ({x}, {y}), inside the boss or off the dais");
        }
    }

    /// The air beside the dais's shoulders is floor to a ray and refused to a step, and
    /// only to a raider's step: the lobby never reads the dais.
    ///
    /// This is the property `map::DAIS` exists for. The dais narrows upward above its
    /// widest row, so a shoulder tile has air over it; the alternative was wall there, and
    /// wall there was a stand from which every upward shot died before any part box.
    #[test]
    fn the_air_beside_the_dais_is_open_to_rays_and_closed_to_raiders() {
        // Every western edge of the dais, on every row of the band: the step west off it
        // is refused, and on some rows -- above the widest one at least -- the tile it
        // would have landed on is air rather than wall. Without the second count `DAIS`
        // could be `WALLS` restated and this test would not know.
        let (mut edges, mut air) = (0, 0);
        let mut y = PIT_TOP;
        while y <= PIT_BOT {
            let mut x = TILE;
            while x <= MAP_MAX_XY {
                if standable(ZONE_ARENA, x, y) && !on_dais(x - STEP, y) {
                    edges += 1;
                    air += usize::from(!is_wall(x - STEP, y));
                    assert!(
                        !may_stand_step(ZONE_ARENA, (x, y), (x - STEP, y)),
                        "a raider at ({x}, {y}) may step west off the dais",
                    );
                }
                x += TILE;
            }
            y += TILE;
        }
        assert!(edges > 0, "the dais has no western edge");
        assert!(air > 0, "no dais tile has air beside it: the dais table is the wall table");

        // The lobby ignores the dais entirely. A lobby seat's rule is walls and the band.
        let gate = GATES[0];
        assert!(may_stand_step(ZONE_LOBBY, (gate.min_x, gate.min_y), (gate.min_x, gate.min_y - STEP)));
        assert!(may_stand_step(ZONE_LOBBY, (TILE, TILE), (2 * TILE, TILE)));
        // Off-map is not dais, in the same fail-closed direction as `is_wall`.
        assert!(!on_dais(-1, PIT_TOP) && !on_dais(0, -1) && !on_dais(MAP_MAX_XY + 1, PIT_TOP));
    }

    /// Releasing a seat is what makes leaving visible to everyone else.
    ///
    /// Without it a seat stayed claimed forever: the roster kept rendering the leaver,
    /// `arena_occupants` never fell so `boss_tick`'s wipe check could not fire, and the
    /// leaver's identity blocked their own rejoin. All three are the same missing write.
    #[test]
    fn leaving_frees_the_seat_and_only_for_its_owner() {
        let mut slot = PlayerSlot::zeroed();
        let identity = [7u8; 32];
        claim_seat(&mut slot, 0, 0, 1, [1u8; 32], identity).unwrap();
        assert!(slot.session_pubkey != UNCLAIMED, "seated to begin with");

        // A stranger's identity must not free it. This is the whole reason the identity
        // travels in the argument block when the treasury is what signs.
        let mut other = slot;
        if other.identity == [9u8; 32] {
            panic!("fixture identities must differ");
        }
        assert!(other.session_pubkey != UNCLAIMED);
        other = slot;

        // The owner's does, and it clears the WHOLE slot: `seat_occupied` is a cache of
        // `session_pubkey != 0`, so a half-cleared seat hands the next player a corpse.
        let released = PlayerSlot::zeroed();
        assert_eq!(released.session_pubkey, UNCLAIMED);
        assert_eq!(released.identity, [0u8; 32]);
        assert_eq!(released.zone, ZONE_LOBBY);
        assert_eq!(released.hp, 0);
        assert_eq!(other.identity, identity, "the fixture still holds the owner");
    }

    /// The gate's four refusals, which are the whole of the waiting-room contract that
    /// lives on this side: you must be standing on one, you may pass once, it must be the
    /// raid's gate, and an unclaimed seat may not pass at all.
    ///
    /// `enter_gate` itself needs three `AccountView`s the host cannot build, so the rules
    /// are asserted through [`gate_refusal`], which is the same code path the handler runs.
    #[test]
    fn the_gate_is_one_way_and_only_from_the_gate() {
        let mut slot = PlayerSlot::zeroed();
        claim_seat(&mut slot, 0, 0, 0, [1u8; 32], [2u8; 32]).unwrap();

        // Walking up to it is not standing on it. The client retries this instruction the
        // whole way in, so the refusal has to be its own code or "not there yet" is
        // indistinguishable from "already through".
        assert_eq!(
            gate_refusal(&slot, None).unwrap_err(),
            HeartrotError::NotOnGate.into()
        );

        // Each gate admits, and answers its own tier; every unit just outside a block is
        // refused, on all four sides — including the wall between two doorways, which is
        // what keeps "which gate" a fact rather than a guess.
        for (tier, gate) in GATES.iter().enumerate() {
            let mut on = slot;
            on.x = gate.min_x;
            on.y = gate.max_y;
            assert_eq!(gate_refusal(&on, None), Ok(tier as u8), "gate {tier} admits");
            for (x, y) in [
                (gate.min_x - 1, gate.min_y),
                (gate.max_x + 1, gate.min_y),
                (gate.min_x, gate.min_y - 1),
                (gate.min_x, gate.max_y + 1),
            ] {
                let mut off = slot;
                off.x = x;
                off.y = y;
                assert_eq!(
                    gate_refusal(&off, None).unwrap_err(),
                    HeartrotError::NotOnGate.into()
                );
            }
        }

        // The tier rule. Nobody has opened the raid: any gate, and the answer is the gate.
        // Somebody has: the same gate passes, any other is `WrongGate` — a code with its
        // own number because, unlike `NotOnGate`, the next poll cannot heal it.
        let on_medium = {
            let mut s = slot;
            s.x = GATES[TIER_MEDIUM as usize].min_x;
            s.y = GATES[TIER_MEDIUM as usize].min_y;
            s
        };
        assert_eq!(gate_refusal(&on_medium, None), Ok(TIER_MEDIUM));
        assert_eq!(gate_refusal(&on_medium, Some(TIER_MEDIUM)), Ok(TIER_MEDIUM));
        for other in [TIER_EASY, TIER_HARD] {
            assert_eq!(
                gate_refusal(&on_medium, Some(other)).unwrap_err(),
                HeartrotError::WrongGate.into(),
                "a raid on tier {other} admits nobody through MEDIUM",
            );
        }

        // One way. This refusal is simultaneously the `alive_count` bound and the whole
        // rate limit on a handler that has no tick counter, so a second entry has to fail
        // even standing on the tile it succeeded from — and before the tier is judged.
        let mut through = on_medium;
        through.zone = ZONE_ARENA;
        assert_eq!(
            gate_refusal(&through, Some(TIER_HARD)).unwrap_err(),
            HeartrotError::WrongZone.into(),
            "the zone check must be read before the position and tier checks",
        );

        // A seat that `join` never wrote cannot be walked through: `hp_max == 0` would
        // count toward `alive_count` while never being alive.
        let mut unclaimed = on_medium;
        unclaimed.hp_max = 0;
        assert_eq!(
            gate_refusal(&unclaimed, None).unwrap_err(),
            ProgramError::InvalidAccountData,
        );
    }

    /// The raid's tier is the first raider's gate and nobody else's: the lock opens on an
    /// arena nobody has entered, closes on the first `enter_gate` (`alive_count`) or the
    /// first counted tick (`raid_size`), whichever the reader sees first, and reopens only
    /// with the incarnation — every account on chain reads EASY until then.
    #[test]
    fn the_first_raider_picks_the_tier_and_the_incarnation_clears_it() {
        let mut arena = Arena::zeroed();
        assert_eq!(locked_tier(&arena), None, "a fresh arena is anybody's");

        // What `enter_gate` writes for the first raider, and what it reads for the next.
        arena.difficulty = TIER_HARD;
        arena.alive_count = 1;
        assert_eq!(locked_tier(&arena), Some(TIER_HARD));
        // The first tick counts the raid; a raid whose every raider has since died is
        // still that raid.
        arena.alive_count = 0;
        arena.raid_size = 1;
        assert_eq!(locked_tier(&arena), Some(TIER_HARD), "raid_size locks it too");

        // Back to the lobby is the only unlock, and it lands on EASY — the tuning every
        // account already on devnet carries in this byte.
        arena.phase = PHASE_SETTLED;
        arena.next_affix_seed = [9u8; 32];
        arena.begin_next_incarnation().expect("a settled, rolled arena reincarnates");
        assert_eq!(arena.difficulty, TIER_EASY);
        assert_eq!(locked_tier(&arena), None, "the next raid picks its own gate");
    }

    /// Exit before the crank wakes is the one road out of `ZONE_ARENA` no tick recounts
    /// behind, so the release hands the count back itself -- or the gate a raider walked
    /// and abandoned stays the raid's tier over an empty pit.
    #[test]
    fn leaving_before_the_fight_gives_the_tier_back() {
        let mut arena = Arena::zeroed();
        // What `enter_gate` left: the seat in the pit at full HP, the count at one, the
        // gate it stood in as the raid's tier.
        let mut walked = PlayerSlot::zeroed();
        walked.zone = ZONE_ARENA;
        walked.hp = PLAYER_HP_MAX;
        walked.hp_max = PLAYER_HP_MAX;
        arena.seat_occupied = 1 << 3;
        arena.alive_count = 1;
        arena.difficulty = TIER_HARD;
        assert_eq!(locked_tier(&arena), Some(TIER_HARD));

        release_seat(&mut arena, &mut walked, 3);
        assert_eq!(bytemuck::bytes_of(&walked), bytemuck::bytes_of(&PlayerSlot::zeroed()));
        assert_eq!((arena.seat_occupied, arena.alive_count), (0, 0));
        assert_eq!(locked_tier(&arena), None, "the next raider's gate is the raid's");

        // A seat still in the lobby never counted, and a dead raider mid-fight was already
        // dropped by the tick's recount: neither release moves the count.
        arena.alive_count = 2;
        let mut waiting = PlayerSlot::zeroed();
        waiting.zone = ZONE_LOBBY;
        waiting.hp = PLAYER_HP_MAX;
        release_seat(&mut arena, &mut waiting, 4);
        let mut dead = PlayerSlot::zeroed();
        dead.zone = ZONE_ARENA;
        dead.hp = 0;
        release_seat(&mut arena, &mut dead, 5);
        assert_eq!(arena.alive_count, 2);
    }
